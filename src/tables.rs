/// Computes the PS1 SPU `VP_PITCH` register for a melodic instrument note.
///
/// `pitch_bend` is an unsigned 8-bit value centered at `0x80` (`+/-2` semitones,
/// 64 steps per semitone).
#[inline]
#[must_use]
pub const fn compute_melodic_pitch(base_pitch: u16, note: u8, pitch_bend: u8) -> u16 {
    let coarse = (pitch_bend >> 6) as i32 - 2;
    let mut idx = note as i32 + coarse;
    if idx < 0 {
        idx = 0;
    } else if idx >= NOTE_PITCH_LUT.len() as i32 {
        idx = (NOTE_PITCH_LUT.len() - 1) as i32;
    }
    let mut pitch = ((NOTE_PITCH_LUT[idx as usize] as u64) * (base_pitch as u64)) >> 12;
    let fine = (pitch_bend & 0x3F) as usize;
    if fine != 0 {
        let factor = (FINE_PITCH_LUT[fine] as u64) + 0x10_0000;
        pitch = ((pitch & 0xFFFF) * factor) >> 20;
    }
    if pitch > 0x3FFF {
        0x3FFF
    } else {
        pitch as u16
    }
}

/// Computes the PS1 SPU `VP_PITCH` register for a percussion or standard SFX voice.
///
/// `pitch_bend` is an unsigned 8-bit value centered at `0x80` (`+/-1` octave).
#[inline]
#[must_use]
pub const fn compute_percussion_pitch(base_pitch: u16, pitch_bend: u8) -> u16 {
    if pitch_bend == CENTER_PARAM {
        return base_pitch;
    }
    let scaled = ((base_pitch as u64) * (PITCH_SCALE_1OCT_LUT[pitch_bend as usize] as u64)) >> 16;
    if scaled > 0x3FFF {
        0x3FFF
    } else {
        scaled as u16
    }
}

/// Computes the PS1 SPU `VP_PITCH` register for a wide-range (`+/-2` octave) SFX voice.
#[inline]
#[must_use]
pub const fn compute_wide_pitch(base_pitch: u16, pitch_bend: u8) -> u16 {
    if pitch_bend == CENTER_PARAM {
        return base_pitch;
    }
    let scaled = ((base_pitch as u64) * (PITCH_SCALE_2OCT_LUT[pitch_bend as usize] as u64)) >> 16;
    if scaled > 0x3FFF {
        0x3FFF
    } else {
        scaled as u16
    }
}

/// Applies constant-power stereo panning to a clamped SPU voice volume.
#[inline]
#[must_use]
pub const fn compute_stereo_volume(volume: u32, pan: u8, stereo: bool) -> (i16, i16) {
    let clamped = if volume > MAX_SPU_VOLUME {
        MAX_SPU_VOLUME
    } else {
        volume
    };
    if !stereo {
        let mono = clamped as i16;
        return (mono, mono);
    }
    let left = ((clamped * (PAN_LUT[255 - pan as usize] as u32)) >> 8) as i16;
    let right = ((clamped * (PAN_LUT[pan as usize] as u32)) >> 8) as i16;
    (left, right)
}
